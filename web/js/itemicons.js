// ── 아이콘 생성 ───────────────────────────────────────────────────────
const ICON_INDEX = {};       // 아이템 이름 -> 스프라이트 칸 번호
let ICON_ATLAS_TILES = 40;   // 한 변 칸 수 (아이템 수에 맞춰 조정)
let ICON_ATLAS_CANVAS = null;
let ICON_ATLAS_URL = '';

const _tintCache = {};

// 아틀라스 타일을 밝기 조절해 복사 (같은 텍스처는 재사용)
function tintedTile(atlasCanvas, texName, factor) {
  const key = texName + '|' + factor;
  if (_tintCache[key]) return _tintCache[key];
  const t = texUV(texName);
  const c = document.createElement('canvas');
  c.width = TILE; c.height = TILE;
  const ctx = c.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(atlasCanvas, t.canvasX, t.canvasY, TILE, TILE, 0, 0, TILE, TILE);
  if (factor !== 1) {
    const img = ctx.getImageData(0, 0, TILE, TILE);
    const d = img.data;
    for (let i = 0; i < d.length; i += 4) {
      d[i] *= factor; d[i + 1] *= factor; d[i + 2] *= factor;
    }
    ctx.putImageData(img, 0, 0);
  }
  _tintCache[key] = c;
  return c;
}

// 아트 마스크를 16x16 캔버스로
function artTile(shape, matKey) {
  const art = ART[shape] || ART.ball;
  const mat = MATERIALS[matKey] || MATERIALS.stone;
  const p = new Pix(16);
  const pal = { M: mat.M, m: mat.m, X: mat.X, H: '#6b4f2c', h: '#4e3820' };
  Object.keys(SHAPE_COLORS).forEach(function (k) { pal[k] = SHAPE_COLORS[k]; });
  if (matKey === 'water') pal.w = '#3f7fe0';
  if (matKey === 'lava') pal.w = '#ff9c22';
  if (matKey === 'milk') pal.w = '#ffffff';
  if (matKey && matKey.indexOf('potion_') === 0) pal.w = mat.M;
  if (matKey && matKey.indexOf('stew') >= 0) pal.w = mat.X;
  if (matKey && matKey.indexOf('soup') >= 0) pal.w = mat.X;
  p.art(art, pal);

  const c = document.createElement('canvas');
  c.width = 16; c.height = 16;
  const ictx = c.getContext('2d');
  const img = ictx.createImageData(16, 16);
  img.data.set(p.data);
  ictx.putImageData(img, 0, 0);
  return c;
}

// 블록 아이템: 아이소메트릭 정육면체를 아틀라스에 직접 그린다
function drawBlockIcon(ctx, atlasCanvas, blockId, ox, oy) {
  const d = blockDef(blockId);
  const s = ICON_SIZE / 16;

  // 십자형/판형 블록은 정면 텍스처를 그대로
  if (d.render === RENDER_CROSS) {
    const t = texUV(d.texSide);
    ctx.drawImage(atlasCanvas, t.canvasX, t.canvasY, TILE, TILE, ox, oy, ICON_SIZE, ICON_SIZE);
    return;
  }

  const top = tintedTile(atlasCanvas, d.texTop, 1.0);
  const left = tintedTile(atlasCanvas, d.texSide, 0.78);
  const right = tintedTile(atlasCanvas, d.texSide, 0.58);

  // 모양에 따라 큐브 높이를 줄여 반블록/카펫 등을 구분한다
  let hScale = 1, yShift = 0;
  if (d.render === RENDER_BOXES && d.boxes && d.boxes.length) {
    let maxY = 0;
    for (let i = 0; i < d.boxes.length; i++) maxY = Math.max(maxY, d.boxes[i][4]);
    hScale = Math.max(0.18, Math.min(1, maxY));
    yShift = (1 - hScale) * 8;
  }

  function face(img, a, b, cc, dd, e, f) {
    ctx.save();
    ctx.setTransform(a * s, b * s, cc * s, dd * s, (e * s) + ox, (f * s) + oy);
    ctx.drawImage(img, 0, 0, TILE, TILE, 0, 0, 1, 1);
    ctx.restore();
  }
  const h = 8 * hScale;
  face(left, 8, 4, 0, h, 0.5, 3.5 + yShift);
  face(right, 8, -4, 0, h, 8, 7.5 + yShift);
  face(top, 8, -4, 8, 4, 0.5, 3.5 + yShift);
  ctx.setTransform(1, 0, 0, 1, 0, 0);
}

// 전체 아이콘을 하나의 스프라이트 시트로
function buildItemIcons(atlasCanvas) {
  const n = ITEM_LIST.length;
  ICON_ATLAS_TILES = Math.ceil(Math.sqrt(n));
  const size = ICON_ATLAS_TILES * ICON_SIZE;

  const canvas = document.createElement('canvas');
  canvas.width = size; canvas.height = size;
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;

  for (let i = 0; i < n; i++) {
    const item = ITEM_LIST[i];
    const tx = i % ICON_ATLAS_TILES, ty = Math.floor(i / ICON_ATLAS_TILES);
    const ox = tx * ICON_SIZE, oy = ty * ICON_SIZE;
    ICON_INDEX[item.name] = i;

    if (item.icon.shape === 'block') {
      drawBlockIcon(ctx, atlasCanvas, item.icon.block, ox, oy);
    } else {
      const tile = artTile(item.icon.shape, item.icon.mat);
      ctx.drawImage(tile, 0, 0, 16, 16, ox, oy, ICON_SIZE, ICON_SIZE);
    }
  }

  ICON_ATLAS_CANVAS = canvas;
  ICON_ATLAS_URL = canvas.toDataURL();
  return canvas;
}

// ── 조회 ──────────────────────────────────────────────────────────────
function iconAtlasURL() { return ICON_ATLAS_URL; }

// DOM 슬롯용 배경 스타일 (스프라이트 시트)
function iconStyle(name) {
  const i = ICON_INDEX[name];
  if (i === undefined) return '';
  const n = ICON_ATLAS_TILES;
  const col = i % n, row = Math.floor(i / n);
  const pct = 100 / (n - 1);
  return 'background-size:' + (n * 100) + '% ' + (n * 100) + '%;' +
    'background-position:' + (col * pct) + '% ' + (row * pct) + '%;';
}

// WebGL(떨어진 아이템)용 UV.
// GL 아틀라스는 균일 축소본이라 정규화 UV가 그대로 통한다. 축소로 인한
// 이웃 아이콘 번짐을 막기 위해 여유(inset)를 넉넉히 준다.
const ICON_UV_INSET_TEXELS = 1.5;
function itemUV(name) {
  const i = ICON_INDEX[name];
  if (i === undefined) return null;
  const n = ICON_ATLAS_TILES;
  const col = i % n, row = Math.floor(i / n);
  const inset = ICON_UV_INSET_TEXELS / (n * ICON_SIZE);
  return {
    u0: col / n + inset, v0: row / n + inset,
    u1: (col + 1) / n - inset, v1: (row + 1) / n - inset
  };
}

// 3D 렌더용 아틀라스: WebGL 1은 밉맵을 쓰려면 2의 거듭제곱 크기여야 한다.
// 전체를 균일하게 축소하므로 UV 좌표는 바뀌지 않는다.
function buildItemAtlasGL() {
  const src = ICON_ATLAS_CANVAS;
  let size = 1;
  while (size * 2 <= src.width) size *= 2;   // src 이하의 가장 큰 2의 거듭제곱
  size = Math.min(size, 1024);
  const out = document.createElement('canvas');
  out.width = size; out.height = size;
  const ctx = out.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(src, 0, 0, size, size);
  return out;
}

// ── 3D 아이템 메시 ────────────────────────────────────────────────────
// 마인크래프트는 떨어진 아이템을 납작한 그림이 아니라 "두께가 있는 판"으로
// 그린다. 아이콘 타일의 알파를 16×16 마스크로 읽어, 테두리 픽셀마다
// 옆면을 세워 진짜 입체로 만든다. 아이템 종류마다 한 번만 계산해 캐시한다.

const ITEM_MESH_RES = 16;          // 아이콘을 몇 칸으로 볼 것인가
const ITEM_MESH_THICK = 1.5 / 16;  // 두께 (블록 1칸 = 1.0 기준)
const ITEM_MESH_CACHE = {};
let ICON_PIXELS = null;

// 아이콘 아틀라스 픽셀을 딱 한 번만 읽어 둔다 (getImageData 는 느리다)
function iconAtlasPixels() {
  if (ICON_PIXELS) return ICON_PIXELS;
  if (!ICON_ATLAS_CANVAS) return null;
  const ctx = ICON_ATLAS_CANVAS.getContext('2d', { willReadFrequently: true });
  ICON_PIXELS = ctx.getImageData(0, 0, ICON_ATLAS_CANVAS.width, ICON_ATLAS_CANVAS.height);
  return ICON_PIXELS;
}

// 면 방향별 밝기 (돌아갈 때 입체감이 살도록)
const ITEM_FACE_SHADE = { front: 1.0, back: 0.88, side: 0.74, top: 1.0, bottom: 0.58 };

// name -> { v: Float32Array(x,y,z,u,v,shade …), idx: Uint16Array }
// 로컬 좌표는 가로·세로 -0.5~0.5, 두께는 ±ITEM_MESH_THICK/2.
function itemMesh(name) {
  const hit = ITEM_MESH_CACHE[name];
  if (hit !== undefined) return hit;

  const img = iconAtlasPixels();
  const idx = ICON_INDEX[name];
  if (!img || idx === undefined) { ITEM_MESH_CACHE[name] = null; return null; }

  const n = ICON_ATLAS_TILES;
  const col = idx % n, row = Math.floor(idx / n);
  const R = ITEM_MESH_RES;
  const step = ICON_SIZE / R;
  const W = img.width, data = img.data;

  // 1) 알파 마스크
  const mask = new Uint8Array(R * R);
  for (let py = 0; py < R; py++) {
    const ay = Math.floor(row * ICON_SIZE + py * step + step * 0.5);
    for (let px = 0; px < R; px++) {
      const ax = Math.floor(col * ICON_SIZE + px * step + step * 0.5);
      mask[py * R + px] = data[(ay * W + ax) * 4 + 3] > 128 ? 1 : 0;
    }
  }
  const at = function (px, py) {
    if (px < 0 || py < 0 || px >= R || py >= R) return 0;
    return mask[py * R + px];
  };

  // 2) 기하 만들기
  const v = [], ind = [];
  const t = ITEM_MESH_THICK * 0.5;
  // 아이콘 칸(0~R) -> 아틀라스 UV
  const uAt = function (px) { return (col + px / R) / n; };
  const vAt = function (py) { return (row + py / R) / n; };
  // 앞뒤 면은 타일 전체를 쓰되 이웃 아이콘이 번지지 않게 여유를 준다
  const uv = itemUV(name);

  function quad(pts, shade) {
    const b = v.length / 6;
    for (let i = 0; i < 4; i++) {
      const p = pts[i];
      v.push(p[0], p[1], p[2], p[3], p[4], shade);
    }
    ind.push(b, b + 1, b + 2, b, b + 2, b + 3);
  }

  // 앞면 (+Z) / 뒷면 (-Z)
  const face = [
    [-0.5, -0.5, uv.u0, uv.v1], [0.5, -0.5, uv.u1, uv.v1],
    [0.5, 0.5, uv.u1, uv.v0], [-0.5, 0.5, uv.u0, uv.v0]
  ];
  quad(face.map(function (c) { return [c[0], c[1], t, c[2], c[3]]; }), ITEM_FACE_SHADE.front);
  quad(face.slice().reverse().map(function (c) { return [c[0], c[1], -t, c[2], c[3]]; }),
       ITEM_FACE_SHADE.back);

  const X = function (px) { return px / R - 0.5; };
  const Y = function (py) { return 0.5 - py / R; };

  // 좌·우 옆면 — 세로로 이어진 구간을 한 장으로 합친다
  for (let px = 0; px < R; px++) {
    for (const dir of [-1, 1]) {
      const x = dir < 0 ? X(px) : X(px + 1);
      let py = 0;
      while (py < R) {
        if (!at(px, py) || at(px + dir, py)) { py++; continue; }
        let end = py;
        while (end + 1 < R && at(px, end + 1) && !at(px + dir, end + 1)) end++;
        const yTop = Y(py), yBot = Y(end + 1);
        const u = uAt(px + 0.5), v0 = vAt(py), v1 = vAt(end + 1);
        if (dir < 0) {
          quad([[x, yBot, -t, u, v1], [x, yBot, t, u, v1],
                [x, yTop, t, u, v0], [x, yTop, -t, u, v0]], ITEM_FACE_SHADE.side);
        } else {
          quad([[x, yBot, t, u, v1], [x, yBot, -t, u, v1],
                [x, yTop, -t, u, v0], [x, yTop, t, u, v0]], ITEM_FACE_SHADE.side);
        }
        py = end + 1;
      }
    }
  }

  // 위·아래 옆면 — 가로로 이어진 구간을 한 장으로 합친다
  for (let py = 0; py < R; py++) {
    for (const dir of [-1, 1]) {
      const y = dir < 0 ? Y(py) : Y(py + 1);
      let px = 0;
      while (px < R) {
        if (!at(px, py) || at(px, py + dir)) { px++; continue; }
        let end = px;
        while (end + 1 < R && at(end + 1, py) && !at(end + 1, py + dir)) end++;
        const x0 = X(px), x1 = X(end + 1);
        const vv = vAt(py + 0.5), u0 = uAt(px), u1 = uAt(end + 1);
        if (dir < 0) {
          quad([[x0, y, t, u0, vv], [x1, y, t, u1, vv],
                [x1, y, -t, u1, vv], [x0, y, -t, u0, vv]], ITEM_FACE_SHADE.top);
        } else {
          quad([[x0, y, -t, u0, vv], [x1, y, -t, u1, vv],
                [x1, y, t, u1, vv], [x0, y, t, u0, vv]], ITEM_FACE_SHADE.bottom);
        }
        px = end + 1;
      }
    }
  }

  const mesh = { v: new Float32Array(v), idx: new Uint16Array(ind), quads: ind.length / 6 };
  ITEM_MESH_CACHE[name] = mesh;
  return mesh;
}
